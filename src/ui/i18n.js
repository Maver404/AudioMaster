/** Both dictionaries; keys are identical (tests/i18n.test.mjs enforces it). */
export const STRINGS = { it, en };
/** Supported language codes. */
export const LANGUAGES = ['it', 'en'];

function storedLanguage() {
  try {
    const v = globalThis.localStorage?.getItem(STORAGE_KEY);
    return LANGUAGES.includes(v) ? v : null;
  } catch {
    return null;
  }
}

// Italian-first product (RESEARCH §5): Italian unless the user picked English with the
// IT/EN toggle (remembered in localStorage). The browser locale is deliberately ignored:
// many Italian musicians run an English OS.
function detectLanguage() {
  return storedLanguage() || 'it';
}

let current = detectLanguage();
const listeners = new Set();

/** @returns {'it'|'en'} the active language. */
export function getLanguage() {
  return current;
}

/**
 * Switch language, persist it (best effort) and notify listeners.
 * @param {'it'|'en'} lang
 */
export function setLanguage(lang) {
  if (!LANGUAGES.includes(lang)) return;
  const changed = lang !== current;
  current = lang;
  try {
    globalThis.localStorage?.setItem(STORAGE_KEY, lang);
  } catch {
    /* storage blocked: keep the in-memory choice */
  }
  try {
    if (globalThis.document?.documentElement) globalThis.document.documentElement.lang = lang;
  } catch {
    /* not in a browser */
  }
  if (changed) for (const fn of [...listeners]) {
    try {
      fn(lang);
    } catch (e) {
      console.error(e);
    }
  }
}

/**
 * Subscribe to language changes.
 * @param {(lang: string) => void} fn
 * @returns {() => void} unsubscribe
 */
export function onLanguageChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/**
 * Locale-aware number: decimal comma in Italian, true minus sign (U+2212), no "−0,0".
 * @param {number} v
 * @param {number} [decimals] default 0 for integers, else 1
 * @param {{ sign?: boolean }} [opts] sign: prefix '+' on positive values
 * @returns {string} '—' for non-finite input
 */
export function formatNumber(v, decimals, opts = {}) {
  if (typeof v !== 'number' || !Number.isFinite(v)) return '—';
  const d = decimals ?? (Number.isInteger(v) ? 0 : 1);
  const abs = Math.abs(v).toFixed(d);
  const isZero = Number(abs) === 0;
  const body = current === 'it' ? abs.replace('.', ',') : abs;
  if (v < 0 && !isZero) return '−' + body;
  if (opts.sign && v > 0 && !isZero) return '+' + body;
  return body;
}

/** 300 → '300 Hz', 3400 → '3,4 kHz', 16000 → '16 kHz'. */
export function formatHz(hz) {
  if (typeof hz !== 'number' || !Number.isFinite(hz)) return '—';
  if (Math.abs(hz) >= 1000) {
    const k = hz / 1000;
    return formatNumber(k, Math.abs(k - Math.round(k)) < 0.05 ? 0 : 1) + ' kHz';
  }
  return formatNumber(Math.round(hz), 0) + ' Hz';
}

/**
 * Seconds → 'm:ss' (or 'm:ss.d' with tenths).
 * @param {number} sec
 * @param {boolean} [tenths]
 */
export function formatTime(sec, tenths = false) {
  if (typeof sec !== 'number' || !Number.isFinite(sec) || sec < 0) sec = 0;
  const total = tenths ? Math.floor(sec * 10) / 10 : Math.floor(sec);
  const m = Math.floor(total / 60);
  const s = total - m * 60;
  const ss = tenths ? s.toFixed(1).padStart(4, '0') : String(Math.floor(s)).padStart(2, '0');
  return `${m}:${current === 'it' && tenths ? ss.replace('.', ',') : ss}`;
}

/**
 * Translate `key` in the active language and interpolate `{name}` placeholders.
 * Numbers are formatted with formatNumber; missing vars keep their placeholder so a
 * contract mismatch is visible instead of silently blank. Unknown keys return the key.
 * @param {string} key
 * @param {Record<string, unknown>} [vars]
 * @returns {string}
 */
export function t(key, vars) {
  let s = STRINGS[current]?.[key];
  if (s === undefined) s = STRINGS.it[key] ?? STRINGS.en[key];
  if (s === undefined) return String(key);
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, name) => {
    const v = vars[name];
    if (v === undefined || v === null) return m;
    if (typeof v === 'number') return formatNumber(v);
    return String(v);
  });
}
